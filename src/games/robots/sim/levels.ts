import type { Role } from "./robots";

/**
 * Map legend:
 *   #  wall          .  floor        S  robot spawn   G  reactor (goal)   C  energy core
 *   ~  gap           =  bridgeable gap               D  door             T  terminal
 *   L  laser         P  pressure plate                B  heavy block   R  rubble
 * Every level links its switches through `channels`: a terminal opens the doors with its digit,
 * a pressed plate switches off the lasers with its digit.
 */
export interface LevelDef {
  id: string;
  name: string;
  tier: number;
  /** Episode length in ticks; tight enough that random play often fails. */
  timeLimit: number;
  description: string;
  robots: Role[];
  map: string[];
  /**
   * Linked switches: same size as `map`, with a digit 1-9 on terminal,
   * door, plate and laser tiles. A terminal opens only doors with its digit and
   * a plate switches off only lasers with its digit. Without it every switch is
   * on one shared channel.
   */
  channels?: string[];
}

